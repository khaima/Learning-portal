/* ============================================================
   HPF Digital Learning Portal — service worker.
   GENERATED by scripts/build-sw.mjs from sw-template.js on every build:
   VERSION is a hash of everything the build produced, and the file lists
   come from the build — nothing here is written by hand.

   Keeps the APP itself on the device, so the portal opens without a
   connection. It never touches data: the API, files and anything signed
   in go straight to the network — data offline lives in IndexedDB per
   account (offline.js), where it can be cleared on sign-out.

   What a device keeps (low data on slow school connections):
   - CORE, on every device: the pages, the icons, the stylesheets and the
     sign-in page's code;
   - the code a device has actually used (a teacher's dashboard, the M&E
     pages someone opens…), kept as it's first loaded and carried into
     each new version. A role never downloads another role's code.
   Built files have a fingerprint in their name, so a copy never goes
   stale: they're served from the device, and a new version reuses every
   file that didn't change instead of downloading it again.

   A new version installs in the background and then WAITS: the page shows
   "Update available — reload" (pwa.js), and it starts only when the person
   chooses — never switched under them in the middle of their work. The
   very first version on a device starts at once.
   ============================================================ */

const VERSION = "__VERSION__";
/** Kept on every device: pages, icons, stylesheets, the sign-in page's code ("" is the site's own address). */
const CORE = __CORE__;
/** Every fingerprinted file in this version (static/name-[hash].ext). */
const FILES = __FILES__;
const FONT_HOSTS = ["fonts.googleapis.com", "fonts.gstatic.com"];
/** Which files this device has used — by name, without the fingerprint. */
const USED_KEY = "__hpf-used.json";

const SCOPE = self.registration.scope;
const at = (path) => new URL(path, SCOPE).href;
const fileSet = new Set(FILES);
/** "static/console-CYAAK4Pb.js" → "static/console.js": the same file across versions. */
const identity = (path) => path.replace(/-[\w-]{8}(\.[a-z0-9]+)$/i, "$1");
const byIdentity = new Map(FILES.map((f) => [identity(f), f]));

/** The names of the files this device has used, from any version's cache. */
async function readUsed() {
  const used = new Set();
  for (const key of await caches.keys()) {
    if (!key.startsWith("hpf-")) continue;
    const res = await (await caches.open(key)).match(at(USED_KEY));
    if (!res) continue;
    try { for (const id of await res.json()) used.add(id); } catch { /* ignore */ }
  }
  return used;
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(VERSION);
    const used = await readUsed();
    const want = new Set(CORE);
    for (const id of used) if (byIdentity.has(id)) want.add(byIdentity.get(id));
    // One by one: a single missing file mustn't leave the device with nothing.
    await Promise.all([...want].map(async (path) => {
      const url = at(path);
      if (fileSet.has(path)) {
        // A fingerprinted file never changes: reuse the copy already here.
        const old = await caches.match(url);
        if (old) return cache.put(url, old);
      }
      return cache.add(new Request(url, { cache: "reload" })).catch(() => {});
    }));
    await cache.put(at(USED_KEY), new Response(JSON.stringify([...used]), { headers: { "content-type": "application/json" } }));
    // No skipWaiting() here: the page asks for it when the person reloads (pwa.js).
  })());
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== VERSION && key.startsWith("hpf-")) await caches.delete(key);
    await self.clients.claim();
  })());
});

/** Remember that this device uses a file, so the next version keeps it too.
    One shared list: files fetched at the same moment all land in it. */
let usedLoading = null;
async function noteUsed(path) {
  usedLoading ??= readUsed();
  const used = await usedLoading;
  const id = identity(path);
  if (used.has(id)) return;
  used.add(id);
  const cache = await caches.open(VERSION);
  await cache.put(at(USED_KEY), new Response(JSON.stringify([...used]), { headers: { "content-type": "application/json" } }));
}

/** The device's copy, or the network (kept for next time). */
async function fromCache(request, path) {
  const cache = await caches.open(VERSION);
  const hit = await cache.match(request, { ignoreSearch: request.mode === "navigate" });
  if (hit) return hit;
  const res = await fetch(request);
  if (res.ok) {
    await cache.put(request, res.clone());
    if (fileSet.has(path)) await noteUsed(path);
  }
  return res;
}

/** Network first for the fonts; the device's copy if the network fails or takes over 4 s. */
async function networkFirst(request) {
  const cache = await caches.open(VERSION);
  const cached = await cache.match(request);
  const network = fetch(request).then((res) => {
    if (res && (res.ok || res.type === "opaque")) cache.put(request, res.clone()).catch(() => {});
    return res;
  });
  network.catch(() => {});
  if (!cached) return network;
  const timeout = new Promise((resolve) => setTimeout(() => resolve(null), 4000));
  return (await Promise.race([network.catch(() => null), timeout])) || cached;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return; // never a write
  const url = new URL(request.url);
  if (url.origin === self.location.origin && request.url.startsWith(SCOPE)) {
    const path = url.pathname.slice(new URL(SCOPE).pathname.length) || "index.html";
    if (path === "sw.js" || path === USED_KEY) return;
    event.respondWith(fromCache(request, path).catch(async () => {
      // Offline and not on the device: the sign-in page for a page address, else nothing.
      if (request.mode === "navigate") {
        const start = await caches.match(at("index.html"));
        if (start) return start;
      }
      return new Response("You're offline and this isn't on this device yet.", { status: 503, headers: { "content-type": "text/plain; charset=utf-8" } });
    }));
    return;
  }
  if (FONT_HOSTS.includes(url.hostname)) event.respondWith(networkFirst(request));
  // Everything else — the API, Supabase, signed file links — goes to the network untouched.
});
